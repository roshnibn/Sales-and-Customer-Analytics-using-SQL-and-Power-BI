-- ============================================================
-- STAR SCHEMA PROJECT - 800 TOTAL ROWS
-- MySQL 8.0+
-- Total rows: 100 Customers + 50 Products + 20 Stores
--            + 130 Dates + 500 Sales = 800 rows
